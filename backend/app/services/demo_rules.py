def seed_published_rules_if_needed(db: Session):
    existing_rules = db.query(Rule).all()
    existing_by_code = {r.rule_code: r for r in existing_rules}

    seeded_rules = []
    for r_dict in RULES_CATALOG:
        r_code = r_dict["rule_code"]
        if r_code not in existing_by_code:
            rule_obj = Rule(
                code=r_code,
                rule_code=r_code,
                category=r_dict["category"],
                title=r_dict["title"],
                description=r_dict["description"],
                handbook_reference=r_dict["handbook_reference"],
                handbook_ref=r_dict["handbook_reference"],
                version=r_dict["version"],
                is_mandatory=r_dict["is_mandatory"],
                rule_type=r_dict["rule_type"],
                severity=r_dict.get("severity", "MAJOR"),
                mandatory=r_dict["is_mandatory"],
                applies_to_categories=r_dict.get("applies_to_categories", ["EOA"]),
                definition=r_dict.get("definition"),
                evidence_required=r_dict.get("evidence_required", []),
                suggested_action=r_dict.get("suggested_action"),
                status="PUBLISHED",
                current_version=1,
                is_active=True,
            )
            db.add(rule_obj)
            seeded_rules.append(rule_obj)
        else:
            seeded_rules.append(existing_by_code[r_code])

    db.commit()

    active_ruleset = db.query(RuleSet).filter(RuleSet.status == "ACTIVE").first()
    if not active_ruleset:
        ruleset = RuleSet(
            name="APH 2026-27",
            version_label="v1.0",
            status="ACTIVE",
            snapshot={
                "published_at": datetime.now(timezone.utc).isoformat(),
                "rules": [
                    {
                        "code": r.code,
                        "title": r.title,
                        "severity": r.severity,
                        "mandatory": r.mandatory,
                        "definition": r.definition,
                    }
                    for r in seeded_rules
                ],
            },
            published_at=datetime.now(timezone.utc),
        )
        db.add(ruleset)
        db.commit()

